/**
 * App-level domain types (persisted to AsyncStorage), distinct from the
 * over-the-wire protocol types in ./protocol.ts.
 */

/** One raw sample captured during a monitoring session (kept in memory only). */
export interface SessionSample {
  pitch: number;
  base: number;
  dev: number;
  alert: 0 | 1;
  /** ms since epoch when the sample was received on the phone. */
  timestamp: number;
}

/** Persisted summary of one completed monitoring session. */
export interface SessionSummary {
  id: string;
  /** ms since epoch. */
  startedAt: number;
  /** ms since epoch. */
  endedAt: number;
  /** Number of samples captured. */
  sampleCount: number;
  /** Percentage (0-100) of samples where alert === 0. */
  correctnessPct: number;
  /** Average absolute deviation across the session, in degrees. */
  avgDeviation: number;
  /** Number of distinct alert episodes (alert 0->1 transitions). */
  alertEpisodes: number;
  /** Was this session generated by demo mode? */
  demo: boolean;
  /**
   * Downsampled pitch/alert series (kept small - a few dozen points) used to
   * draw the "angle across the day" chart on the Day Detail screen without
   * persisting every raw sample.
   */
  samples?: SessionSamplePoint[];
}

export interface SessionSamplePoint {
  /** ms since session start. */
  offsetMs: number;
  pitch: number;
  alert: 0 | 1;
}

/** Aggregated stats for a single calendar day (YYYY-MM-DD, local time). */
export interface DayAggregate {
  date: string;
  usageMs: number;
  avgAngle: number;
  correctnessPct: number;
  alertCount: number;
  sessionCount: number;
}

export interface UserProfile {
  name: string;
  age: string;
  heightCm: string;
  goal: string;
}

export interface AppSettings {
  vibrationEnabled: boolean;
  soundEnabled: boolean;
  pushEnabled: boolean;
  /** 0..1 slider value; maps inversely to SET_THRESH degrees (0 -> 20deg, 1 -> 5deg). */
  sensitivity: number;
  /** Repeat-alert interval in ms, while alert stays true. */
  alertIntervalMs: number;
  demoMode: boolean;
  /** Remembered paired device, so "Start monitoring" can auto-reconnect. */
  lastDeviceAddress?: string;
  lastDeviceName?: string;
}

export interface AchievementProgress {
  id: string;
  unlocked: boolean;
  progress: number; // 0..1
}
